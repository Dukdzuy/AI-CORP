/**
 * Project Repository Interface
 * Follows Dependency Inversion Principle (SOLID)
 * Domain layer defines the contract, infrastructure implements it
 */

import { MilestoneDTO } from './IMilestoneRepository';
import { TaskDTO } from './ITaskRepository';
import { WorkflowRunDTO } from './IWorkflowRepository';

export interface ProjectDTO {
  id: string;
  name: string;
  description: string;
  goal: string;
  status: string;
  budget: number | null;
  costAccrued: number;
  createdById: string;
  createdAt: Date;
  updatedAt: Date;
  /** Latest top-level workflow run; set by findAll for the project list's progress */
  latestRun?: ProjectRunSummary | null;
}

export interface ProjectRunSummary {
  id: string;
  status: string;
  currentNodeId: string | null;
  workflowDefId: string;
  workflowDefVersion: string | null;
  /** Position of currentNodeId in the run's definition (filled in by the application service) */
  nodeIndex?: number;
  nodeCount?: number;
}

export interface CreateProjectData {
  /** Identity assigned by the Project entity; generated by the database when omitted */
  id?: string;
  name: string;
  description: string;
  goal: string;
  budget?: number | null;
  createdById: string;
}

export interface UpdateProjectData {
  name?: string;
  description?: string;
  goal?: string;
  status?: string;
  budget?: number | null;
  costAccrued?: number;
}

/**
 * Repository interface for Project aggregate
 * Abstracts data access layer from domain logic
 */
export interface IProjectRepository {
  /**
   * Find project by ID
   */
  findById(id: string): Promise<ProjectDTO | null>;

  /**
   * Find all projects with optional ordering
   */
  findAll(options?: {
    orderBy?: 'createdAt' | 'updatedAt';
    order?: 'asc' | 'desc';
  }): Promise<ProjectDTO[]>;

  /**
   * Find all projects created by a specific user
   */
  findByUserId(userId: string): Promise<ProjectDTO[]>;

  /**
   * Create a new project
   */
  create(data: CreateProjectData): Promise<ProjectDTO>;

  /**
   * Update an existing project
   */
  update(id: string, data: UpdateProjectData): Promise<ProjectDTO>;

  /**
   * Delete a project and all related data
   */
  delete(id: string): Promise<void>;

  /**
   * Increment project cost and auto-pause if budget exceeded
   */
  updateCost(id: string, amount: number): Promise<ProjectDTO>;

  /**
   * Find project with its milestones
   */
  findWithMilestones(id: string): Promise<(ProjectDTO & { milestones: MilestoneDTO[] }) | null>;

  /**
   * Find project with its tasks
   */
  findWithTasks(id: string): Promise<(ProjectDTO & { tasks: TaskDTO[] }) | null>;

  /**
   * Find project with workflow runs
   */
  findWithWorkflowRuns(
    id: string,
    limit?: number
  ): Promise<(ProjectDTO & { workflowRuns: WorkflowRunDTO[] }) | null>;
}
